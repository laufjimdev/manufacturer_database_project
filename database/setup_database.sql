-- ===========================================
-- setup_database.sql
-- Manufacturing Operations Database
-- Orchestrates a from-scratch build by running, in order:
--   1. roles.sql    cluster-wide group + login roles, memberships
--   2. (this file)  CREATE DATABASE + database-level CONNECT
--   3. schema.sql   tables, constraints, indexes
--   4. grants.sql   schema, column and table privileges
--
-- Run with psql (NOT psycopg2): CREATE DATABASE cannot run inside a
-- transaction, and this script uses \ir, \connect and \gexec.
--
--   psql -h <host> -U lauradev -d postgres -v ON_ERROR_STOP=1 \
--        -v db_name=manufacturer_db -f database/setup_database.sql
--
-- Requirements:
--   * PostgreSQL 16+
--   * Run as the owner/superuser (lauradev), connected to the
--     maintenance database "postgres" (not the target database)
--   * roles.sql, schema.sql and grants.sql sit in the same folder as
--     this file (\ir resolves paths relative to the including file)
--   * Passwords are NOT set here. Assign them separately.
--
-- Intended for fresh databases: schema.sql's ADD CONSTRAINT lines
-- fail if the constraints already exist. roles.sql and grants.sql
-- can be re-run on their own at any time.
-- ===========================================

\set ON_ERROR_STOP on

-- Default database name if -v db_name=... was not supplied.
\if :{?db_name}
\else
    \set db_name manufacturer_db
\endif


------------------------------------------------------------
-- 1. ROLES
------------------------------------------------------------

\ir roles.sql


------------------------------------------------------------
-- 2. DATABASE
-- Generated by a query and run with \gexec because CREATE DATABASE
-- cannot be used in a DO block. Skipped if it already exists.
------------------------------------------------------------

SELECT format('CREATE DATABASE %I OWNER lauradev', :'db_name')
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = :'db_name')
\gexec

-- Only the groups below may connect (members inherit CONNECT).
REVOKE ALL ON DATABASE :"db_name" FROM PUBLIC;

GRANT CONNECT ON DATABASE :"db_name"
    TO dba, production_manager, maintenance_manager,
       read_only_auditor, sales_analyst, warehouse_staff;


------------------------------------------------------------
-- 3. SCHEMA
------------------------------------------------------------

\connect :db_name

\ir schema.sql


------------------------------------------------------------
-- 4. GRANTS
------------------------------------------------------------

\ir grants.sql

-- ===========================================
-- END OF SETUP
